#!/usr/bin/env python3
"""Refreshes the model rates that ship inside Maggie.

The usage panel prices sessions from LiteLLM's model_prices_and_context_window.json.
The app downloads that file about once a day, but a first launch, an offline Mac or
an upstream change must not leave the panel blank, so a trimmed copy is compiled into
the app as `macos/Sources/Features/Usage/UsageBundledRates.swift`.

Run this before a release to pick up new prices:

    python3 fork/update-rates.py

Only the models Maggie can meet are kept (Anthropic and OpenAI families), and only the
fields `UsageRateTable` reads. The result is a few dozen kilobytes.
"""

import json
import subprocess
import sys
from datetime import date
from pathlib import Path

SOURCE = "https://raw.githubusercontent.com/BerriAI/litellm/main/model_prices_and_context_window.json"
TARGET = Path(__file__).resolve().parent.parent / "macos/Sources/Features/Usage/UsageBundledRates.swift"

FIELDS = (
    "input_cost_per_token",
    "output_cost_per_token",
    "cache_read_input_token_cost",
    "cache_creation_input_token_cost",
    "cache_creation_input_token_cost_above_1hr",
)
PROVIDERS = {"anthropic", "openai"}


def wanted(name: str, entry: dict) -> bool:
    """Only the two providers' own entries: Claude Code and Codex report the bare model
    names those are keyed by. Resellers' copies (bedrock, vertex, proxies) add nothing."""
    if not isinstance(entry, dict):
        return False
    if "input_cost_per_token" not in entry or "output_cost_per_token" not in entry:
        return False
    return str(entry.get("litellm_provider", "")).lower() in PROVIDERS


def main() -> int:
    # curl rather than urllib: a python.org Python has no certificate store of its own.
    fetched = subprocess.run(["curl", "-fsSL", "--max-time", "60", SOURCE], capture_output=True, text=True)
    if fetched.returncode != 0:
        print(f"could not download the rates: {fetched.stderr.strip()}", file=sys.stderr)
        return 1
    document = json.loads(fetched.stdout)

    trimmed = {}
    for name in sorted(document):
        entry = document[name]
        if not wanted(name, entry):
            continue
        trimmed[name] = {field: entry[field] for field in FIELDS if field in entry}

    if len(trimmed) < 50:
        print(f"only {len(trimmed)} models matched; refusing to write a thin table", file=sys.stderr)
        return 1

    body = json.dumps(trimmed, indent=1, sort_keys=True)
    swift = f'''// Generated by fork/update-rates.py on {date.today().isoformat()}. Do not edit by hand.
//
// The model rates that ship inside the app, trimmed from LiteLLM's
// model_prices_and_context_window.json to the models Maggie can meet. The scanner
// prices from this table until it has downloaded a fresher one.

enum UsageBundledRates {{
    /// How many models the bundled table holds, for tests.
    static let modelCount = {len(trimmed)}

    /// The day the table was generated.
    static let generatedOn = "{date.today().isoformat()}"

    static let json = #"""
{body}
"""#
}}
'''
    TARGET.write_text(swift)
    print(f"wrote {TARGET.relative_to(TARGET.parents[4])}: {len(trimmed)} models, {len(body) // 1024} KB")
    return 0


if __name__ == "__main__":
    sys.exit(main())
